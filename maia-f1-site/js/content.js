function wave(n, { base, amp, cycles, phase = 0, decay = 0 }) {
  return Array.from({ length: n }, (_, i) => {
    const t = i / (n - 1);
    return base + amp * Math.sin(2 * Math.PI * cycles * t + phase) * (1 - decay * t);
  });
}

